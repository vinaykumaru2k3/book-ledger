/** Turns the palettes into CSS custom properties. Pure; used by `npm run themes` and the tests. */
import { contrast, mix, triplet } from "../../shared/lib/color.js";
import { DEFAULT_THEME, PALETTES } from "./palettes.js";

/** Every `--pk-*` colour variable for one palette, in the order they are written. */
export function themeVariables(p) {
  const dark = p.mode === "dark";
  const toward = dark ? "#ffffff" : "#000000";
  const soft = (color) => mix(p.bg, color, dark ? 0.2 : 0.14);
  const shadow = dark ? "0, 0, 0" : triplet(mix(p.ink, p.accent, 0.35));
  /** Brightens a jewel so it reads on the dark night panels even in light themes. */
  const lit = (color) => (dark ? color : mix(color, p.cream, 0.5));
  const night = [p.night, p.night2, p.night3];

  return {
    "color-scheme": p.mode,
    "--pk-bg": p.bg,
    "--pk-surface": p.surface,
    "--pk-surface-rgb": triplet(p.surface),
    "--pk-surface-raised": p.raised,
    "--pk-surface-sunken": p.sunken,
    "--pk-ink": p.ink,
    "--pk-ink-2": p.ink2,
    "--pk-ink-3": p.ink3,
    "--pk-ink-rgb": triplet(p.ink),
    "--pk-line": `rgba(${triplet(p.ink)}, ${dark ? 0.14 : 0.11})`,
    "--pk-line-strong": `rgba(${triplet(p.ink)}, ${dark ? 0.28 : 0.22})`,

    "--pk-night": night[0],
    "--pk-night-2": night[1],
    "--pk-night-3": night[2],
    "--pk-night-rgb": triplet(p.night),
    "--pk-cream": p.cream,
    "--pk-cream-2": `rgba(${triplet(p.cream)}, 0.76)`,
    "--pk-cream-3": `rgba(${triplet(p.cream)}, 0.6)`,
    "--pk-cream-rgb": triplet(p.cream),
    "--pk-night-line": mix(p.night3, p.cream, 0.12),
    "--pk-night-sky": `radial-gradient(60% 90% at 100% 0%, rgba(${triplet(p.accent)}, 0.34), transparent 70%), radial-gradient(55% 85% at 0% 100%, rgba(${triplet(p.gilt)}, 0.12), transparent 70%), linear-gradient(135deg, ${p.night2}, ${p.night} 70%)`,

    "--pk-accent": p.accent,
    "--pk-accent-hover": mix(p.accent, toward, dark ? 0.16 : 0.18),
    "--pk-accent-soft": soft(p.accent),
    "--pk-accent-rgb": triplet(p.accent),
    "--pk-on-accent": p.onAccent,

    "--pk-gilt": p.gilt,
    "--pk-gilt-2": mix(p.gilt, p.night, 0.25),
    "--pk-gilt-rgb": triplet(p.gilt),
    "--pk-gold": p.gold,
    "--pk-gold-rgb": triplet(p.gold),
    "--pk-gold-soft": soft(p.gold),
    "--pk-gilt-sheen": `linear-gradient(100deg, ${mix(p.gilt, "#000000", 0.25)}, ${p.gilt} 45%, ${mix(p.gilt, "#000000", 0.12)} 70%, ${mix(p.gilt, "#ffffff", 0.3)})`,

    "--pk-sapphire": p.blue,
    "--pk-sapphire-rgb": triplet(p.blue),
    "--pk-emerald": p.green,
    "--pk-emerald-rgb": triplet(p.green),
    "--pk-emerald-bright": dark ? p.green : mix(p.green, "#ffffff", 0.4),
    "--pk-amethyst": p.purple,
    "--pk-amethyst-rgb": triplet(p.purple),
    "--pk-copper": p.orange,
    "--pk-peacock": p.teal,
    "--pk-garnet-bright": dark ? p.red : mix(p.red, "#ffffff", 0.2),

    "--pk-star-done": lit(p.green),
    "--pk-star-reading": p.gilt,
    "--pk-star-want": lit(p.blue),
    "--pk-star-dusk": mix(p.night, p.cream, 0.5),
    "--pk-star-favorite": lit(p.red),
    "--pk-star-link": mix(p.night, p.cream, 0.18),

    "--pk-success-soft": soft(p.green),
    "--pk-warning": p.warn,
    "--pk-warning-soft": soft(p.warn),
    "--pk-danger": p.red,
    "--pk-danger-rgb": triplet(p.red),
    "--pk-danger-soft": soft(p.red),
    "--pk-focus": p.focus,
    "--pk-focus-rgb": triplet(p.focus),

    "--pk-shadow-rgb": shadow,
    "--pk-shadow-1": `0 1px 2px rgba(${shadow}, ${dark ? 0.4 : 0.08}), 0 1px 1px rgba(${shadow}, ${dark ? 0.24 : 0.04})`,
    "--pk-shadow-2": `0 6px 18px rgba(${shadow}, ${dark ? 0.42 : 0.1}), 0 1px 3px rgba(${shadow}, ${dark ? 0.3 : 0.06})`,
    "--pk-shadow-3": `0 22px 50px rgba(${shadow}, ${dark ? 0.55 : 0.2}), 0 4px 12px rgba(${shadow}, ${dark ? 0.35 : 0.08})`,
  };
}

const block = (selector, vars) => `${selector} {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;

/** The whole of themes.css. The default theme also answers to `:root`, so there is never a colourless frame. */
export function buildThemesCss() {
  const header = "/* GENERATED by `npm run themes` from src/features/theme/palettes.js. Do not edit by hand. */\n";
  return (
    header +
    PALETTES.map((palette) => {
      const selector = palette.id === DEFAULT_THEME ? `:root,\n:root[data-theme="${palette.id}"]` : `:root[data-theme="${palette.id}"]`;
      return `\n/* ${palette.name} */\n${block(selector, themeVariables(palette))}`;
    }).join("")
  );
}

/** Contrast checks every theme must pass: [label, foreground, background, minimum ratio]. */
export function contrastChecks(p) {
  const nightText2 = mix(p.night, p.cream, 0.76);
  const nightText3 = mix(p.night, p.cream, 0.6);
  const checks = [
    ["ink on page", p.ink, p.bg, 4.5],
    ["ink on card", p.ink, p.surface, 4.5],
    ["secondary on page", p.ink2, p.bg, 4.5],
    ["secondary on card", p.ink2, p.surface, 4.5],
    ["muted on page", p.ink3, p.bg, 4.5],
    ["muted on card", p.ink3, p.surface, 4.5],
    ["muted on well", p.ink3, p.sunken, 4.5],
    ["muted on menu", p.ink3, p.raised, 4.5],
    ["button text", p.onAccent, p.accent, 4.5],
    ["accent link on page", p.accent, p.bg, 4.5],
    ["accent link on card", p.accent, p.surface, 4.5],
    ["gold on page", p.gold, p.bg, 4.5],
    ["blue on page", p.blue, p.bg, 4.5],
    ["green on page", p.green, p.bg, 4.5],
    ["red on page", p.red, p.bg, 4.5],
    ["warning on page", p.warn, p.bg, 4.5],
    ["purple on page", p.purple, p.bg, 3],
    ["orange on page", p.orange, p.bg, 3],
    ["teal on page", p.teal, p.bg, 3],
    ["cream on night", p.cream, p.night, 4.5],
    ["cream-2 on night", nightText2, p.night, 4.5],
    ["cream-3 on night", nightText3, p.night, 4.5],
    ["cream-3 on night-3", mix(p.night3, p.cream, 0.6), p.night3, 3],
    ["gilt on night", p.gilt, p.night, 4.5],
    ["night text on gilt", p.night, p.gilt, 4.5],
  ];
  return checks.map(([label, fg, bg, min]) => ({ label, fg, bg, min, ratio: contrast(fg, bg) }));
}
